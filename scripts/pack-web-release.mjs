#!/usr/bin/env node
// 组装 ZCode Web Server headless 发布目录（详见 packages/server/specs/web-server-bundle.md）。
// 只做拷贝/改名/生成启动脚本，不做任何编译；所有输入必须先构建完成，缺失即整体失败。
//
// 用法：node scripts/pack-web-release.mjs --target linux-arm64 [--out-dir release/zcode-web-linux-arm64]

import { chmod, copyFile, mkdir, readdir, rm, stat, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const SUPPORTED_TARGETS = new Set(["linux-x64", "linux-arm64"]);

function parseArgs(argv) {
  const parsed = { target: undefined, outDir: undefined };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--target") {
      parsed.target = argv[i + 1];
      i += 1;
    } else if (arg === "--out-dir") {
      parsed.outDir = argv[i + 1];
      i += 1;
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }
  if (!parsed.target) {
    throw new Error("Missing --target <linux-x64|linux-arm64>");
  }
  if (!SUPPORTED_TARGETS.has(parsed.target)) {
    throw new Error(
      `Unsupported target "${parsed.target}". Supported: ${[...SUPPORTED_TARGETS].join(", ")}.`,
    );
  }
  return parsed;
}

async function assertFile(path, label) {
  const info = await stat(path);
  if (!info.isFile()) {
    throw new Error(`${label} is not a file: ${path}`);
  }
}

async function assertReadableFile(path, label) {
  if (!existsSync(path)) {
    throw new Error(`${label} not found (expected: ${path}). Build it before packing.`);
  }
  await assertFile(path, label);
}

async function copyDirectory(sourceDir, targetDir, { excludeExtensions = [] } = {}) {
  await mkdir(targetDir, { recursive: true });
  const entries = await readdir(sourceDir, { withFileTypes: true });
  for (const entry of entries) {
    const sourcePath = join(sourceDir, entry.name);
    const targetPath = join(targetDir, entry.name);
    if (entry.isDirectory()) {
      await copyDirectory(sourcePath, targetPath, { excludeExtensions });
    } else if (
      entry.isFile() &&
      !excludeExtensions.some((extension) => entry.name.endsWith(extension))
    ) {
      await copyFile(sourcePath, targetPath);
    }
  }
}

function renderStartScript(target) {
  return [
    "#!/usr/bin/env bash",
    "# Generated by scripts/pack-web-release.mjs — paths are bound to this directory.",
    "set -euo pipefail",
    "",
    'DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"',
    "# Agent 解析要求 cwd 位于包根（bundled-agents 候选路径按 cwd 解析）。",
    'cd "$DIR"',
    "",
    "# Bundled web UI (served by the same process, SPA fallback).",
    'export ZCODE_WEB_STATIC_ROOT="$DIR/web"',
    "",
    "# Bundled agent binary. The server never resolves the agent from PATH.",
    `export GLM_BINARY_PATH="$DIR/bundled-agents/${target}/glm/zcode-agent"`,
    "",
    'export PORT="${PORT:-3030}"',
    "",
    'exec node "$DIR/server/zcode-web-server.cjs"',
    "",
  ].join("\n");
}

function renderReadme(target) {
  return `# ZCode Web Server (${target})

A self-contained, headless build of the ZCode Web client: the web UI, the API/WebSocket
server, and the agent CLI binary in one directory. No desktop or display dependencies.

## Requirements

- Linux ${target === "linux-arm64" ? "arm64 (aarch64)" : "x86_64"}
- Node.js >= 22 on \`PATH\`

## Quick start

\`\`\`bash
tar xzf zcode-web-${target}.tar.gz
cd zcode-web-${target}
./start.sh
# open http://localhost:3030
\`\`\`

## Configuration (environment variables)

| Variable | Default | Purpose |
| --- | --- | --- |
| \`PORT\` | \`3030\` | HTTP/WebSocket listen port. |
| \`ZCODE_SERVER_HOST\` | all interfaces | Bind address (e.g. \`127.0.0.1\`). |
| \`ZCODE_SERVER_AUTH_TOKEN\` | unset | When set, API requests require this bearer token. Set this before exposing the server beyond localhost. |
| \`ZCODE_WEB_STATIC_ROOT\` | bundled \`web/\` | Override to serve a different UI build. |
| \`GLM_BINARY_PATH\` | bundled agent | Override to use a different agent CLI binary. |

## Layout

\`\`\`
server/zcode-web-server.cjs        single-file API/WebSocket server
server/build/Release/pty.node      terminal support (node-pty)
web/                               static web UI
bundled-agents/${target}/glm/zcode-agent   agent CLI binary
\`\`\`

State (provider config, sessions, settings) is stored under \`~/.zcode/\`.
`;
}

async function main() {
  const { target, outDir: outDirArg } = parseArgs(process.argv.slice(2));
  const outDir = resolve(rootDir, outDirArg ?? `release/zcode-web-${target}`);

  const serverBundlePath = join(rootDir, "packages/server/dist/remote/zcode-web-server.cjs");
  const serverNoticesPath = join(rootDir, "packages/server/dist/remote/THIRD-PARTY-NOTICES.md");
  const webDistDir = join(rootDir, "packages/web/dist");
  const agentBinaryPath = join(rootDir, "apps/zcode-cli/packages/cli/dist", `zcode-${target}`);
  const ptyPrebuildPath = join(
    rootDir,
    "node_modules",
    `@lydell/node-pty-${target}`,
    "prebuilds",
    target,
    "pty.node",
  );

  await assertReadableFile(
    serverBundlePath,
    "server http bundle (pnpm --filter @zcode/server build:remote:http)",
  );
  await assertReadableFile(serverNoticesPath, "third-party notices");
  await assertReadableFile(
    join(webDistDir, "index.html"),
    "web dist (pnpm --filter @zcode/web build)",
  );
  await assertReadableFile(agentBinaryPath, `agent SEA binary (zcode-${target})`);
  await assertReadableFile(
    ptyPrebuildPath,
    `node-pty prebuild (@lydell/node-pty-${target}; requires a full pnpm install)`,
  );

  await rm(outDir, { recursive: true, force: true });

  // pty.node 固定放在 bundle 旁的 build/Release/：node-pty 在单文件 bundle 里按
  // 相对路径 require 该文件，与 stdio 远端部署布局（remoteAssetDeployDecision.ts）同构。
  const serverDir = join(outDir, "server");
  await mkdir(join(serverDir, "build", "Release"), { recursive: true });
  await copyFile(serverBundlePath, join(serverDir, "zcode-web-server.cjs"));
  await copyFile(serverNoticesPath, join(serverDir, "THIRD-PARTY-NOTICES.md"));
  await copyFile(ptyPrebuildPath, join(serverDir, "build", "Release", "pty.node"));

  // vite 生产构建输出 hidden sourcemap（无 sourceMappingURL 引用，仅供符号服务上传），
  // 随包分发没有消费方且占 ~60% 体积，打包时剔除。
  await copyDirectory(webDistDir, join(outDir, "web"), { excludeExtensions: [".map"] });

  // Agent 二进制按 findZCodeAgentRuntimeBinary 的 bundled-agents 候选布局落盘并改名。
  const agentTargetPath = join(outDir, "bundled-agents", target, "glm", "zcode-agent");
  await mkdir(dirname(agentTargetPath), { recursive: true });
  await copyFile(agentBinaryPath, agentTargetPath);
  await chmod(agentTargetPath, 0o755);

  const startScriptPath = join(outDir, "start.sh");
  await writeFile(startScriptPath, renderStartScript(target), "utf-8");
  await chmod(startScriptPath, 0o755);

  await writeFile(join(outDir, "README.md"), renderReadme(target), "utf-8");

  console.log(`Packed zcode-web-${target} -> ${outDir}`);
  console.log(`  server/zcode-web-server.cjs + build/Release/pty.node + notices`);
  console.log(`  web/ (static UI)`);
  console.log(`  bundled-agents/${target}/glm/zcode-agent`);
  console.log(`  start.sh + README.md`);
}

main().catch((error) => {
  console.error(`[pack-web-release] ${error instanceof Error ? error.message : error}`);
  process.exitCode = 1;
});
